MAP_W, MAP_H = 144, 72
MAP_LON0, MAP_LON1 = -180.0, 180.0
MAP_LAT0, MAP_LAT1 = -60.0, 85.0


def map_xy(lon, lat, x, y, w, h):
    """Project lon/lat to pixels inside the map box."""
    fx = (lon - MAP_LON0) / (MAP_LON1 - MAP_LON0)
    fy = (MAP_LAT1 - lat) / (MAP_LAT1 - MAP_LAT0)
    return x + int(fx * w), y + int(fy * h)


def draw_map(cv, x, y, w, h, dots):
    """Draw the land mask as small blocks, then red dots for story places."""
    cell_w = w / MAP_W
    cell_h = h / MAP_H
    bw = max(2, int(cell_w) + 1)
    bh = max(2, int(cell_h) + 1)
    for r, row in enumerate(MAP_ROWS):
        for c, ch in enumerate(row):
            if ch == "#":
                cv.rect(x + int(c * cell_w), y + int(r * cell_h),
                        bw, bh, (168, 168, 160))
    for lon, lat in dots:
        dx, dy = map_xy(lon, lat, x, y, w, h)
        cv.circle(dx, dy, 4, RED)
        cv.circle(dx, dy, 2, (255, 255, 255))


