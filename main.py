def text_width(s, scale, spacing=None):
    if spacing is None:
        spacing = scale
    adv = 5 * scale + spacing
    return len(s) * adv - spacing if s else 0


def draw_text(cv, x, y, s, scale, color, bold=False, spacing=None):
    if spacing is None:
        spacing = scale
    adv = 5 * scale + spacing
    cx = x
    for ch in s:
        glyph = FONT.get(ch, FONT["?"])
        for gy, row in enumerate(glyph):
            for gx, cell in enumerate(row):
                if cell == "#":
                    cv.rect(cx + gx * scale, y + gy * scale,
                            scale, scale, color)
                    if bold:
                        cv.rect(cx + gx * scale + 1, y + gy * scale,
                                scale, scale, color)
        cx += adv
    return cx


def draw_centered(cv, cx, y, s, scale, color, bold=False, spacing=None):
    w = text_width(s, scale, spacing)
    return draw_text(cv, cx - w // 2, y, s, scale, color, bold, spacing)


def fit_scale(s, max_w, max_scale):
    """Largest scale (down to 1) that fits s inside max_w pixels."""
    for sc in range(max_scale, 0, -1):
        if text_width(s, sc) <= max_w:
            return sc
    return 1


def wrap(s, scale, max_w, spacing=None):
    """Greedy word wrap into lines that fit max_w."""
    if spacing is None:
        spacing = scale
    adv = 5 * scale + spacing
    per = max(1, (max_w + spacing) // adv)
    words = s.split(" ")
    lines = []
    cur = ""
    for word in words:
        trial = word if not cur else cur + " " + word
        if len(trial) <= per:
            cur = trial
        else:
            if cur:
                lines.append(cur)
            while len(word) > per:
                lines.append(word[:per])
                word = word[per:]
            cur = word
    if cur:
        lines.append(cur)
    return lines


